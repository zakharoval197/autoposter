"""
filter.py — отсев мусора по ключевым словам.

Логика:
1. DROP_KEYWORDS в любом поле -> выбросить (новости, реклама, вакансии).
2. Ни одного KEEP_KEYWORDS -> выбросить (не похоже на событие).
Цель по брифу: отсекать минимум 70% мусора.
"""

import logging

logger = logging.getLogger("autoposter.filter")

# Маркеры мусора: новости, реклама, вакансии, статьи
DROP_KEYWORDS = [
    "ваканси", "требуется", "ищем в команду", "резюме",
    "скидк", "промокод", "розыгрыш", "конкурс подпис",
    "сообщил", "заявил", "по данным", "интервью",
    "обзор рынка", "рейтинг", "топ-10", "топ 10",
    "открытие филиала", "франшиз", "инвести", "недвижимост",
    "прогноз", "спрогноз", "пожаловал", "разбился", "погиб",
    "штраф", "задержан", "скандал", "пересда", "вышел альбом",
    "вышел клип", "выпустили клип", "выпустил клип",
    "собянин", "бпла", "предрекл", "призвал",  # протокольные новости mos.ru/m24
    # отчёты и итоги (это новости о прошедшем, не афиша)
    "как прошёл", "как прошла", "прошёл фестиваль", "состоял", "итоги",
    "подвели итоги", "завершился", "завершилась", "вспоминаем",
    # закрытые мероприятия (подписчику туда не попасть)
    "вручение наград", "награждение", "приглашения рассылаются",
    "продажа билетов отсутствует", "закрытое мероприятие", "по приглашениям",
]
# "новости" убран: режет mos.ru («Новости» в описаниях) и живые анонсы

# Маркеры события: хотя бы одно должно встретиться.
# ВНИМАНИЕ: ищем подстрокой, поэтому короткие маркеры шумят:
# "маркет" ловил "маркетолог", "сет" — "совет/сеть" (поймано 05.10).
KEEP_KEYWORDS = [
    "концерт", "вечеринка", "выставка", "спектакль", "лекци",
    "мастер-класс", "кинопоказ", "премьера", "фестиваль", "фест",
    " бар", "клуб", "вечер", "показ", "экскурси", "ярмарка",
    "стендап", "standup", "джаз", "техно", "сет ",
    "иммерсивн", "перформанс", "квиз", "шоу", "оркестр",
    "мюзикл", "опера", "балет", "симфони", "квартирник",
]

# Чужие города: если встретились и при этом нет «москв» — не наша афиша.
# Канал московский, события Питера/Архангельска/Израиля не нужны.
NON_MSK_MARKERS = [
    "петербург", "питер", "спб", "архангельск", "казан", "новосибирск",
    "екатеринбург", "сочи", "израил", "самара", "нижни", "краснодар",
    "ростов", "крым", "уфа", "омск", "владивосток", "калининград",
    "ярославл", "вологд", "рязан", "тула", "пермь", "челябинск",
    "красноярск",
]


def _text_of(event: dict) -> str:
    parts = [
        event.get("title") or "",
        event.get("description") or "",
        event.get("venue") or "",
    ]
    return " ".join(parts).lower()


def check(event: dict) -> tuple[bool, str]:
    """Возвращает (прошёл_фильтр, причина)."""
    text = _text_of(event)
    trusted = bool(event.get("trusted"))  # доверенная афиша (mos.ru)
    for kw in DROP_KEYWORDS:
        if kw in text:
            return False, f"мусор: маркер «{kw}»"
    if not trusted:
        for kw in NON_MSK_MARKERS:
            if kw in text and "москв" not in text and "мск" not in text:
                return False, f"не Москва: маркер «{kw}»"
        for kw in KEEP_KEYWORDS:
            if kw in text:
                return True, f"ок: маркер «{kw}»"
        return False, "мусор: нет ни одного маркера события"
    return True, "ок: доверенный источник"


def filter_events(events: list[dict]) -> tuple[list[dict], list[dict]]:
    """Разделяет список на (прошедшие, отфильтрованные)."""
    kept, dropped = [], []
    for ev in events:
        ok, reason = check(ev)
        if ok:
            logger.info("ФИЛЬТР ✔ %s (%s)", ev.get("title"), reason)
            kept.append(ev)
        else:
            logger.info("ФИЛЬТР ✘ %s (%s)", ev.get("title"), reason)
            dropped.append(ev)
    logger.info(
        "Фильтр: прошло %d, отсеяно %d из %d", len(kept), len(dropped), len(events)
    )
    return kept, dropped
